/** The merge context, from the employee card plus what the manager fills in. */
function buildContext(employee, { branch, overrides = {} } = {}) {
  const variant = overrides.variant || (employee.salary_type === 'global' ? 'global' : 'hourly');
  const dist = (employee.amuta_distribution || [])[0] || {};
  const bank = [employee.bank_number && `בנק ${employee.bank_number}`,
    employee.bank_branch && `סניף ${employee.bank_branch}`,
    employee.bank_account && `חשבון ${employee.bank_account}`].filter(Boolean).join(', ');

  const base = {
    variant,
    employee_name: employee.full_name || '',
    israeli_id: employee.israeli_id || '',
    address: employee.address || '',
    phone: employee.phone || '',
    email: employee.email || '',
    position: employee.position || '',
    branch_name: branch?.name || '',
    start_date: longDate(employee.start_date),
    signed_on: new Date(),
    signed_place: 'כפר סבא',
    supervisor: '',
    hourly_rate: dist.hourly_rate || null,
    monthly_salary: dist.global_salary || null,
    required_hours: dist.required_hours || null,
    bank_text: bank,
    pension_text: employee.pension_fund ? `קרן הפנסיה מצויה בחברת ${employee.pension_fund}.` : '',
    religion: '',
    school_year_start: '', school_year_end: '', camp_end: '',
    weekday_start: '', weekday_end: '', friday_start: '', friday_end: '',
    weekly_hours: (employee.fixed_schedule?.days || []).map(d => ({
      weekday: d.weekday, in: d.in, out: d.out, note: '',
    })),
    job_definition: jobDefinitionFor(employee.position),
    annex_c: '',
    // Filled by the controller from the standing ContractAnnex parts, so the
    // contract lists what is actually attached rather than a fixed sentence.
    annex_c_parts: [],
  };
  return { ...base, ...overrides };
}

module.exports = { buildContext, render, jobDefinitionFor, JOB_DEFINITIONS, longDate };
