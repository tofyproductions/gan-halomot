/**
 * הסכם העסקה — the employment agreement, rendered from the office's own text.
 *
 * The two Word files (שעתי / גלובלי) are the same document apart from the
 * title and the pay clause: hourly says "₪ לשעה", global says "₪ לחודש" and
 * adds a monthly-hours commitment. So there is ONE template here with a
 * variant switch, rather than two texts to keep in sync — a divergence that
 * would otherwise show up as one variant quietly missing a clause the other
 * got.
 *
 * Everything the system already knows is filled in; the blanks that remain are
 * the ones only a human can answer (pension fund, bank, weekly hours).
 *
 * ANNEX A (job definition) is per-position and editable — the supplied file
 * only carries the סייעת version, and handing a גננת the סייעת's duties would
 * be worse than leaving it blank. Defaults live in JOB_DEFINITIONS and the
 * text can be overridden per contract.
 */

const IL_TZ = 'Asia/Jerusalem';

const longDate = (d) => {
  if (!d) return '';
  const dt = new Date(d);
  if (isNaN(dt)) return '';
  return new Intl.DateTimeFormat('en-GB', { timeZone: IL_TZ, day: '2-digit', month: '2-digit', year: 'numeric' })
    .format(dt).replace(/\//g, '.');
};

const dateParts = (d) => {
  if (!d) return { day: '', month: '', year: '' };
  const dt = new Date(d);
  if (isNaN(dt)) return { day: '', month: '', year: '' };
  const p = new Intl.DateTimeFormat('en-GB', { timeZone: IL_TZ, day: '2-digit', month: '2-digit', year: 'numeric' })
    .formatToParts(dt);
  const g = (t) => p.find(x => x.type === t)?.value || '';
  return { day: g('day'), month: g('month'), year: g('year') };
};

const esc = (s) => String(s == null ? '' : s)
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const escLines = (s) => esc(s).replace(/\r?\n/g, '<br/>');

/** A value, or a ruled blank of roughly the right width to write it in. */
const val = (v, width = 150) => (v == null || v === ''
  ? `<span class="blank" style="min-width:${width}pt"></span>`
  : `<span class="filled">${esc(v)}</span>`);

