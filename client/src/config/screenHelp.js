/**
 * What each screen is for, said in the words the person reading it uses.
 *
 * The system has seventy-odd screens and the people who run it are not
 * programmers. They learn a screen by being shown it once, and a year later
 * they use the three parts they were shown and never discover the rest —
 * "רשימון שיחות", "זימון קבוצתי", "העלאת קובץ ביטול" all exist, all do the
 * thing somebody is currently doing by hand, and none of them announce
 * themselves.
 *
 * So every screen carries its own page of help, opened from the same "?" in
 * the same corner, and it answers three questions in this order: what is this
 * screen for, what can I do here, and what does this particular button do. The
 * last section is the one that earns its keep — the questions are the ones
 * actually asked, and the answers are the ones that stop the phone ringing.
 *
 * Keyed by tab id, the same id `screenForPath` returns and the same one the
 * permission system uses, so a screen renamed in the rail keeps its help and a
 * screen that loses its id loudly loses its help too.
 *
 * Deliberately free of React and MUI: it is content, it is checked by
 * scripts/screen-help.test.js under plain node, and the check that every
 * screen has an entry is the thing that stops this file from rotting.
 *
 * Shape:
 *   summary  — one or two sentences. What the screen is FOR, not what it shows.
 *   can      — what a person can do here, one line each, in the order they
 *              would do them.
 *   buttons  — [{ name, what }] for controls whose effect is not obvious from
 *              the label. A button that says exactly what it does needs no row.
 *   faq      — [{ q, a }] the questions that actually get asked.
 *   notes    — warnings and gotchas. Rendered apart, because "this sends an
 *              email to every parent" must not sit in a list of tips.
 */

